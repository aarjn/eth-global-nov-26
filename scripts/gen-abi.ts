// Regenerates packages/shared/src/abi/{PaymentRouter,InvoiceNote}.ts from Foundry output.
// Usage (repo root): bun run gen:abi   (runs `forge build` first unless --no-build)
import { $ } from "bun";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const contractsDir = join(root, "contracts");
const outDir = join(root, "packages/shared/src/abi");
const names = ["PaymentRouter", "InvoiceNote"] as const;

if (!process.argv.includes("--no-build")) {
  const forge = `${process.env.HOME}/.foundry/bin/forge`;
  await $`${forge} build --skip test --skip script`.cwd(contractsDir).quiet();
}

for (const name of names) {
  const artifact = await Bun.file(join(contractsDir, "out", `${name}.sol`, `${name}.json`)).json();
  const abi = JSON.stringify(artifact.abi, null, 2);
  const src =
    `// GENERATED by scripts/gen-abi.ts from contracts/out/${name}.sol/${name}.json. Do not edit.\n` +
    `export const ${name[0]!.toLowerCase()}${name.slice(1)}Abi = ${abi} as const;\n`;
  await Bun.write(join(outDir, `${name}.ts`), src);
  console.log(`wrote packages/shared/src/abi/${name}.ts (${artifact.abi.length} entries)`);
}

await Bun.write(
  join(outDir, "index.ts"),
  `// GENERATED by scripts/gen-abi.ts. Do not edit.\n` +
    names.map((n) => `export * from "./${n}";`).join("\n") +
    `\nexport * from "./helpers";\n`,
);
